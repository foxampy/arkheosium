/* ---------- shared types ---------- */
export interface Manufacturer {
  id: string;
  name: string;
  country: string;
  description: string;
  website: string;
  specialization: string[];
  founded_year: number;
  employees_range: string;
  logo_placeholder: string; // emoji / initials
}

export interface ResearchInstitute {
  id: string;
  name: string;
  country: string;
  description: string;
  website: string;
  specialization: string[];
  founded_year: number;
  logo_placeholder: string;
}

export interface Startup {
  id: string;
  name: string;
  country: string;
  description: string;
  website: string;
  specialization: string[];
  founded_year: number;
  funding: string;
  logo_placeholder: string;
}

export interface Technology {
  id: string;
  name_ru: string;
  name_en: string;
  category: string;
  description: string;
  maturity_level: string; // TRL 1-9 or "commercial"
  applications: string[];
  image_url?: string;
  price_range?: string;
  manufacturer?: string;
  specifications?: Record<string, string>;
  advantages?: string[];
  country_of_origin?: string;
}

export interface Equipment {
  id: string;
  name_ru: string;
  name_en: string;
  category: string;
  description: string;
  maturity_level: string;
  applications: string[];
  image_url?: string;
  price_range?: string;
  manufacturer?: string;
  specifications?: Record<string, string>;
  advantages?: string[];
  country_of_origin?: string;
}

export interface StartupSolution {
  id: string;
  name: string;
  startup_name: string;
  country: string;
  description: string;
  image_url?: string;
  price_range?: string;
  funding_raised?: string;
  year_founded: number;
  category: string;
  specifications?: Record<string, string>;
  website?: string;
}

export interface ResearchProgram {
  id: string;
  name_ru: string;
  name_en: string;
  institution: string;
  country: string;
  description: string;
  category: string;
  year_started: number;
  status: string;
  publications_count?: number;
  funding?: string;
  image_url?: string;
}

