// Crisis level → map marker color for year-slider visualization
export const CRISIS_COLORS: Record<string, string> = {
  normal: "#34d399",
  warning: "#fbbf24",
  critical: "#fb923c",
  catastrophe: "#ff4d6d",
};

export function getObjectColorForYear(obj: PlatformObject, year: number): string {
  if (!obj.historical_data) return getObjectColor(obj.type);
  const sorted = [...obj.historical_data].sort((a, b) => a.year - b.year);
  let closest = sorted[0];
  for (const d of sorted) {
    if (d.year <= year) closest = d;
  }
  if (closest?.crisis_level) return CRISIS_COLORS[closest.crisis_level] ?? getObjectColor(obj.type);
  return getObjectColor(obj.type);
}

export function getObjectValueForYear(obj: PlatformObject, year: number): HistoricalYearData | null {
  if (!obj.historical_data) return null;
  const sorted = [...obj.historical_data].sort((a, b) => a.year - b.year);
  let closest = sorted[0];
  for (const d of sorted) {
    if (d.year <= year) closest = d;
  }
  return closest ?? null;
}

export function getObjectColor(type: string): string {
  return OBJECT_TYPE_COLORS[type] ?? OBJECT_TYPE_COLORS.default;
}

