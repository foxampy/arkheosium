/**
 * Сборки-операционные системы: ArkheOSium, TerrOSium, Ethosium.
 *
 * Главное, что должен понять читатель: это не три компании и не три
 * продукта одной компании. Это три сборки из одной библиотеки узлов —
 * ровно то, что описано в главе об архитектуре. Водный узел учёта
 * ресурса и узел идентичности одинаково нужны реестру земли и реестру
 * здоровья; разными у сборок будут предметная область, политики и
 * юрисдикция, а не устройство.
 *
 * Вторая причина, по которой это данные, а не текст на странице, —
 * дисциплина основания. У каждой сборки есть поле `inContour`: внесена
 * ли она в общий контур разработки. Соблазн написать «экосистема из
 * трёх операционных систем» велик, а правда на сегодня такова, что
 * в общем контуре одна, у второй не найдены исходники, третья прислана
 * документом. Партнёры названы владельцем проекта и помечены как
 * заявленные: договоров не опубликовано, подключённых партнёров ноль
 * во всех трёх сборках.
 */

export interface SystemPartner {
  name: string;
  role: string;
  /**
   * Состояние отношений. Публиковать как партнёрство можно только
   * `signed`, и тогда рядом обязано стоять название документа.
   */
  stage: 'declared' | 'talks' | 'signed';
  /** Ссылка, если сторона имеет публичный адрес. */
  url?: string;
}

export const PARTNER_STAGE_LABEL: Record<SystemPartner['stage'], string> = {
  declared: 'назван владельцем проекта, документ не опубликован',
  talks: 'переговоры',
  signed: 'договор подписан',
};

export interface OSBuild {
  id: string;
  name: string;
  /** Предметная область одной строкой. */
  domain: string;
  /** Что это по сути: какой мир она описывает. */
  about: string;
  url?: string;
  docUrl?: string;
  /** Внесена ли сборка в общий контур разработки. */
  inContour: boolean;
  /** Честная строка состояния: где лежит, что с ней можно делать сейчас. */
  state: string;
  /** Какие узлы библиотеки сборка использует или будет использовать. */
  nodes: string[];
  partners: SystemPartner[];
}

