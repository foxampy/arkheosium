/**
 * Сборки-операционные системы: ArkheOSium (корень), R&D · LabForge,
 * EcologyOSium, ZooOSium, TerrOSium, EthOSium.
 *
 * Главное, что должен понять читатель: это не шесть компаний и не шесть
 * продуктов одной компании. Это сборки из одной библиотеки узлов —
 * ровно то, что описано в главе об архитектуре. Водный узел учёта
 * ресурса и узел идентичности одинаково нужны реестру земли и реестру
 * здоровья; разными у сборок будут предметная область, политики и
 * юрисдикция, а не устройство.
 *
 * Вторая причина, по которой это данные, а не текст на странице, —
 * дисциплина основания. У каждой записи есть два поля состояния.
 * `kind` говорит, чем запись является на сегодня: работающим контуром,
 * внешним адресом или названным направлением, за которым кода нет.
 * `inContour` говорит, внесена ли она в общий контур разработки.
 * Соблазн написать «экосистема из шести операционных систем» велик,
 * а правда на сегодня такова: в общем контуре три записи, и одна из
 * этих трёх — имя над уже работающим ресурсным контуром, а не
 * отдельная сборка. У одной записи не найдены исходники, одна
 * прислана документом, ещё одно имя названо, и кода под ним нет.
 *
 * Партнёры названы владельцем проекта и помечены как заявленные:
 * договоров не опубликовано, подключённых партнёров ноль во всех
 * сборках.
 */

export interface SystemPartner {
  name: string;
  role: string;
  /**
   * Состояние отношений. Публиковать как партнёрство можно только
   * `signed`, и тогда рядом обязано стоять название документа.
   */
  stage: 'declared' | 'talks' | 'signed';
  /** Ссылка, если сторона имеет публичный адрес. */
  url?: string;
}

export const PARTNER_STAGE_LABEL: Record<SystemPartner['stage'], string> = {
  declared: 'назван владельцем проекта, документ не опубликован',
  talks: 'переговоры',
  signed: 'договор подписан',
};

/**
 * Чем запись является на сегодня.
 *
 * Различение нужно, потому что в одном перечне оказались вещи разной
 * природы: работающий контур, внешний сайт и название направления, за
 * которым кода нет. Без этого поля читатель принимает список из шести
 * строк за шесть операционных систем, а строки не равны между собой.
 * Перечислить замысел рядом со сделанным можно — выдать одно за другое
 * нельзя.
 */
export type BuildKind =
  /** Корневая сборка: на ней обкатывается конституция. */
  | 'root'
  /** Сборка с собственным контуром или внешним адресом. */
  | 'build'
  /** Направление названо. Кода под этим именем нет. */
  | 'named';

