export interface OSBuild {
  id: string;
  name: string;
  /** Предметная область одной строкой. */
  domain: string;
  /** Что это по сути: какой мир она описывает. */
  about: string;
  url?: string;
  docUrl?: string;
  kind: BuildKind;
  /** Внесена ли сборка в общий контур разработки. */
  inContour: boolean;
  /** Честная строка состояния: где лежит, что с ней можно делать сейчас. */
  state: string;
  /**
   * Куда ведёт карточка сборки — маршрут её собственного модуля.
   *
   * Поле обязательное и осознанно не `optional`: карточка без перехода
   * оставляет читателя в тупике, а весь смысл витрины в том, чтобы
   * от каждого названия можно было уйти вглубь — в документацию,
   * интерактив и расчёты этого направления.
   */
  moduleTo: string;
  /** Что читатель там найдёт. Пишется как обещание, которое модуль выполняет. */
  moduleLabel: string;
  /** Какие узлы библиотеки сборка использует или будет использовать. */
  nodes: string[];
  partners: SystemPartner[];
}

