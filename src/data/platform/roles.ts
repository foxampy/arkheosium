/**
 * Кто с кем и на каких условиях.
 *
 * У каждой роли три поля, и третье — обязательное. «Что даёт» и «что
 * получает» есть в любой презентации; «чего не получает» нет почти
 * нигде, и именно в этом месте у читателя достраивается то, чего ему
 * не обещали. Инвестор, которому не сказали «доли нет», уходит
 * с мыслью, что доля обсуждаема.
 *
 * Поэтому колонка «чего не получает» здесь не оговорка в подвале,
 * а часть описания роли, и роль без неё в таблицу не попадает.
 */

export interface Role {
  id: string;
  title: string;
  /** Одна строка: кто это. */
  who: string;
  gives: string;
  gets: string;
  /** Что этой роли не даётся. Поле обязательное. */
  notGets: string;
  /** Куда идти на платформе. */
  entry: { label: string; to: string };
}

