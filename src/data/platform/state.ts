/**
 * Состояние платформы числами. Все восемь величин — нули.
 *
 * Ноль вынесен в данные по той же причине, по которой он вообще
 * написан: пропущенный ноль читается как отсутствие темы, а не как
 * отсутствие величины. «Про лицензии ничего не сказано» и «лицензий
 * выдано ноль» — разные сообщения, и второе честнее.
 *
 * Величина названа здесь один раз. Страница для инвесторов, обзорная
 * страница и главы документа берут её отсюда. Разъехаться им негде:
 * чтобы ноль превратился в единицу на одной странице и остался нулём
 * на другой, придётся сначала завести вторую копию — а это видно
 * в диффе.
 */

export interface ZeroFact {
  id: string;
  /** Короткая подпись под числом. Для плитки. */
  short: string;
  /** Полная формулировка. Для главы документа. */
  label: string;
  /** Почему ноль и чем он перестанет быть нулём. */
  note: string;
}

