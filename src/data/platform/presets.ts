/**
 * Готовые конфигурации — то, ради чего вся библиотека вообще собрана
 * из узлов, а не написана одним куском.
 *
 * Разговор с фондом или заказчиком никогда не начинается с библиотеки.
 * Он начинается с «у нас бассейн», «у нас парк насосов», «у нас
 * муниципалитет». Пресет — это ответ на такую фразу за один щелчок:
 * набор узлов, который под эту задачу собирается, и то, чего в этом
 * наборе нет. Показать перестроение вживую можно только если оно
 * действительно перестроение, а не переключение картинок.
 *
 * Поэтому пресет не содержит ни одного собственного узла, ни одного
 * собственного описания и ни одной цифры. Он содержит только список
 * идентификаторов: всё остальное берётся из реестра узлов в момент
 * сборки. Если узел изменит состояние, пресет покажет новое состояние
 * сам — иначе демонстрация «живой структуры» была бы показом слайдов,
 * подписанных как структура.
 *
 * Поле `without` обязательно. Конфигурация без списка того, чего в ней
 * нет, читается как полное решение задачи, и в этом месте собеседник
 * достраивает недостающее сам — ровно то, против чего построена вся
 * остальная разметка оснований.
 */

