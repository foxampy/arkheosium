export interface Preset {
  id: string;
  /** Название так, как задачу называет собеседник. */
  title: string;
  /** Кому это показывают. Одна строка. */
  who: string;
  /** Что конфигурация делает. Без прилагательных. */
  does: string;
  /** Узлы конфигурации. Только идентификаторы — описания берутся из реестра. */
  nodeIds: readonly string[];
  /** Чего в этой конфигурации нет. Поле обязательное. */
  without: string;
  /** К какой сборке относится: arkheosium | terrosium | ethosium. */
  build: string;
}

