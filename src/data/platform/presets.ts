export interface ResolvedPreset extends Preset {
  nodes: PlatformNode[];
  /** Сколько узлов конфигурации имеют код в репозитории. */
  withCode: number;
  /** Сколько прошло стандартизацию. Сегодня по всем конфигурациям ноль. */
  standardized: number;
  /** Суммарный объём узлов конфигурации в строках. */
  lines: number;
}

export function resolvePreset(p: Preset): ResolvedPreset {
  const nodes = p.nodeIds
    .map(nodeById)
    .filter((n): n is PlatformNode => !!n);
  return {
    ...p,
    nodes,
    withCode: nodes.filter((n) => n.lines > 0).length,
    standardized: nodes.filter((n) => n.standardized).length,
    lines: nodes.reduce((s, n) => s + n.lines, 0),
  };
}

export const RESOLVED_PRESETS: readonly ResolvedPreset[] = PRESETS.map(resolvePreset);

export function presetById(id: string): ResolvedPreset | undefined {
  return RESOLVED_PRESETS.find((p) => p.id === id);
}

/**
 * Узлы, не вошедшие ни в один пресет. Величина полезна в разговоре:
 * она отвечает на вопрос «а это вы зачем сделали», и ответ на него
 * должен быть, иначе узел лишний.
 */
export const NODES_OUTSIDE_PRESETS = NODES.filter(
  (n) => !PRESETS.some((p) => p.nodeIds.includes(n.id)),
);
