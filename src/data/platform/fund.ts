/**
 * Работа, которую можно профинансировать. Одна работа — один узел —
 * один проверяемый факт закрытия.
 */
export interface WorkPackage {
  nodeId: string;
  node: PlatformNode;
  /** Что делается. Берётся из узла, здесь не переписывается. */
  work: string;
  /** Чем подтверждается, что работа закрыта. */
  closedBy: string;
  /** Смета. Всегда одно и то же: её нет. */
  estimate: string;
}

