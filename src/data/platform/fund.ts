/**
 * Вход для фонда и инвестора: что здесь есть, чего здесь нет и что
 * именно предлагается профинансировать.
 *
 * Обычная посадочная для инвестора устроена как воронка: сначала
 * обещание, потом крючок, ограничение — в подвале мелким шрифтом.
 * Здесь порядок обратный, и не из скромности. Предложения доходности
 * на платформе не существует: средства не привлекаются, инструмента
 * нет, оценки компании нет. Посадочная, которая выясняет это на шестом
 * экране, за пять экранов до того успевает получить внимание под
 * ложным предлогом — а это и есть то, за что платформу справедливо
 * назвали бы обманом.
 *
 * Поэтому первый шаг отсеивает, а не удерживает: если посетитель ищет
 * доходность, ему прямо сказано уйти. Это стоит трафика и экономит
 * чужое время, и второе здесь считается дороже.
 *
 * Работы, которые можно профинансировать, не выдуманы для этой
 * страницы: каждая берётся из поля `toTransferable` соответствующего
 * узла. Список работ не может разойтись с состоянием узлов, потому что
 * он из них и получен. Смет нет ни у одной работы, и это написано
 * словом «не составлена», а не пропущено.
 */

