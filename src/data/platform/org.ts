/**
 * Одно направление внутри контура — как оно звучит на витрине.
 *
 * Отдельно от `SYSTEMS` не заводится: это функция над реестром сборок.
 */
export interface PartnerRef extends SystemPartner {
  /** Сборка, к которой сторона отнесена. */
  buildId: string;
  buildName: string;
}

/**
 * Собрать список сторон из реестра сборок.
 *
 * Единственный источник — `SYSTEMS`. Если завтра партнёр появится у новой
 * сборки или сменит стадию с `declared` на `signed`, витрина изменится
 * сама, и ни одна страница не останется с устаревшей формулировкой.
 */
export function allPartners(): PartnerRef[] {
  return SYSTEMS.flatMap((s) =>
    s.partners.map((p) => ({ ...p, buildId: s.id, buildName: s.name })),
  );
}

/**
 * Сколько сторон подключено — то есть имеет подписанный документ.
 *
 * Число выведено отдельно, потому что именно его первым делом ищет
 * читатель, и именно его проще всего не написать. На сегодня ноль.
 */
export function signedPartnerCount(): number {
  return allPartners().filter((p) => p.stage === 'signed').length;
}
