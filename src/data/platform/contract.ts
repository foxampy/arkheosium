/**
 * Условия передачи: что уходит с лицензией, что не уходит никогда,
 * что не отключается ни в какой конфигурации и в каком порядке
 * выполняется работа.
 *
 * Эти четыре списка — содержание любого предложения, которое платформа
 * вообще может сделать партнёру. Конструктор предложений на обзорной
 * странице собирает черновик из них и только из них: своих формулировок
 * у конструктора нет, поэтому он не может пообещать больше, чем
 * записано здесь.
 *
 * Ставок в лестнице нет и они помечены пробелом. Опубликованный
 * «ориентир» был бы заявлением о готовности, которой нет: развёртываний
 * ноль, стандартизованных узлов ноль, и выводить цену не из чего.
 */

