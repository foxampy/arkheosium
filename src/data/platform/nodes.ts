/**
 * Библиотека узлов — единственное место, где она перечислена.
 *
 * До этого файла список узлов существовал дважды: таблицей в главе 12
 * и карточками на странице для инвесторов. Два списка одного и того же
 * расходятся не потому, что кто-то ленив, а потому что правку вносят
 * туда, куда смотрят. Ровно так на платформе разъехались три числа
 * эмиссии. Поэтому здесь данные, а глава и страницы — виды.
 *
 * Два поля обязательны и не имеют значения по умолчанию: `have` и
 * `missing`. Строка без `missing` превращает заготовку в готовое
 * изделие — а это и есть основной способ соврать в списке модулей,
 * ничего не выдумывая: просто не сказать, чего в узле нет.
 *
 * Слово «модуль» здесь не используется намеренно. Модуль — это узел,
 * прошедший стандартизацию: с описанным интерфейсом, границами
 * применимости и условиями переиспользования. По этому определению
 * модулей ноль, и производная `STANDARDIZED_COUNT` считает это из
 * данных, а не повторяет числом в тексте.
 */

/** Состояние узла. Процентов готовности здесь нет намеренно: их не из чего выводить. */
export type NodeStatus =
  /** В репозитории есть работающая заготовка. Стандартизацию не проходила. */
  | 'draft'
  /** Узел назван в замысле и не начат. Кода нет. */
  | 'not-started';

export const NODE_STATUS_LABEL: Record<NodeStatus, string> = {
  draft: 'заготовка',
  'not-started': 'не начат',
};

export const NODE_STATUS_COLOR: Record<NodeStatus, string> = {
  draft: '#fbbf24',
  'not-started': '#f87171',
};

export interface PlatformNode {
  id: string;
  /** Название узла так, как оно звучит в разговоре с партнёром. */
  title: string;
  /** Одна строка: для чего узел нужен. Без прилагательных. */
  purpose: string;
  /** Что фактически лежит в репозитории. Обход исходников, не замысел. */
  have: string;
  /** Чего в узле нет. Поле обязательное. */
  missing: string;
  status: NodeStatus;
  /** Прошёл ли стандартизацию. Сегодня — ни один. */
  standardized: boolean;
}

