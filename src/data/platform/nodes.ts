/**
 * Сколько узлов прошло стандартизацию. Считается из данных: если
 * когда-нибудь первый узел её пройдёт, число изменится само, и его не
 * придётся искать по тексту в трёх местах.
 */
export const STANDARDIZED_COUNT = NODES.filter((n) => n.standardized).length;

/** Сколько узлов вообще названо. Тоже производная: список растёт — число растёт. */
export const NODE_COUNT = NODES.length;

/** Сколько узлов имеет код в репозитории. */
export const NODE_WITH_CODE_COUNT = NODES.filter((n) => n.lines > 0).length;

/** Суммарный объём узлов в строках. Мера проделанной работы, не мера готовности. */
export const NODE_LINES_TOTAL = NODES.reduce((s, n) => s + n.lines, 0);

/** Строки таблицы узлов для главы документа. Глава берёт их отсюда, а не переписывает. */
export const NODE_TABLE_ROWS: string[][] = NODES.map((n) => [n.title, n.have, n.missing]);

/** Узлы, сгруппированные по семейству — для видов, которым нужен порядок, а не список. */
export const NODES_BY_FAMILY: { family: NodeFamily; nodes: PlatformNode[] }[] = (
  ['record', 'measure', 'exchange', 'rule', 'surface'] as NodeFamily[]
).map((family) => ({ family, nodes: NODES.filter((n) => n.family === family) }));

export function nodeById(id: string): PlatformNode | undefined {
  return NODES.find((n) => n.id === id);
}
