//  Партнёрские входы — корпус записей
//
//  Восемь входов по числу категорий партнёра. У каждого свой адрес,
//  своя приветственная презентация, свой онбординг, свой срез
//  whitepaper и свой набор позиций витрины.
//
//  Дисциплина корпуса (правило проекта, не стилистика):
//
//  1. Утверждение без основания не вносится. Каждая запись несёт
//     `source` — документ, реестр или файл корпуса. Каждый пункт
//     `pains` либо опирается на этот источник, либо начинается
//     словами «Гипотеза контура:» — и тогда он читается как
//     предположение, а не как установленный факт.
//
//  2. Ставки и суммы не публикуются: ни одна не утверждена. Условия
//     берутся из витрины (PriceTerms: расчёт после разбора задачи,
//     расчёт после технического задания, ставка после согласования
//     объёма, ставка не утверждена, грантовое финансирование).
//     «От N долларов», «экономия до 30%», «окупаемость за полгода» —
//     не встречаются здесь ни разу и не появятся без утверждённой
//     ставки.
//
//  3. Ноль пишется нулём. Подписанных партнёров сейчас нет ни в одном
//     сегменте; в `stateNote` каждого входа это записано числом, а не
//     опущено.
//
//  4. Прогноз помечается как прогноз, заявление вендора отделяется от
//     независимой проверки — так же, как в каталоге модуля «Газнефть».
//
//  5. Неизвестное помечается ⟨заполнить⟩ прямо в тексте поля.
//     Правдоподобная подстановка запрещена.
//
//  ── Откуда взяты числа в `metric` ───────────────────────────────
//
//     96  — объекты домена oilgas: src/data/objects/oilgas-objects.ts (11),
//           oilgas-objects-ext.ts (45), oilgas-objects-uz.ts (40);
//           сумма собирается на странице /oilgas.
//     53  — объекты экологического слоя: src/data/objects/ecology-objects.ts.
//     88  — позиции каталога модуля «Газнефть»: OILGAS_ALL_ITEMS =
//           R&D (6) + методологии (36) + оборудование (16) + услуги (16)
//           + продукты (11) + проекты (3).
//     36  — позиции витрины: SHOWCASE_OFFERINGS.
//     24  — нефтегазовые проекты: src/data/projects/oilgas-projects.ts.
//     23  — водные объекты: WATER_BODIES в src/data/water-bodies-data.ts.
//     17  — субъекты домена oilgas: src/data/subjects/oilgas-subjects.ts.
//      8  — домены классификации: DOMAIN_ORDER в src/lib/domains.ts.
//      4  — организации контура: SHOWCASE_PROVIDERS.
//      0  — внедрения, эмиссии, сертификаты и партнёры там, где их нет.
//
//  ── Маршруты ────────────────────────────────────────────────────
//
//  Все пути в `modules[].path` и `welcome[].link.path` сверены с
