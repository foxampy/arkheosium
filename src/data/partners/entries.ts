/** Карта по ключу сегмента. Используется страницами вида /partners/:key. */
export const ENTRY_BY_KEY: Record<PartnerSegment, PartnerEntry> =
  PARTNER_ENTRIES.reduce((acc, entry) => {
    acc[entry.key] = entry;
    return acc;
  }, {} as Record<PartnerSegment, PartnerEntry>);

/**
 * Карта по пригласительному коду в нижнем регистре: маршрут
 * /invite/:code должен находить вход независимо от того, как код
 * набран — ARKHE-IND-2026, arkhe-ind-2026 или вперемешку.
 */
export const ENTRY_BY_INVITE: Record<string, PartnerEntry> =
  PARTNER_ENTRIES.reduce((acc, entry) => {
    acc[entry.inviteCode.toLowerCase()] = entry;
    return acc;
  }, {} as Record<string, PartnerEntry>);

/**
 * Поиск входа по коду с нормализацией: убираются краевые пробелы,
 * регистр приводится к нижнему. Неизвестный код возвращает undefined —
 * страница обязана показать это как «код не найден», а не молча
 * подставить первый вход.
 */
export function findEntryByInvite(code: string): PartnerEntry | undefined {
  if (!code) return undefined;
  return ENTRY_BY_INVITE[code.trim().toLowerCase()];
}
