// ═══════════════════════════════════════════════════════════════
//  Партнёрские входы — типы
//
//  Отдельный вход для каждой категории партнёра: промышленность,
//  инфраструктура, градостроение, бизнес, корпорации, государства,
//  организации и прочие. У входа своя приветственная презентация,
//  свой онбординг, свой срез whitepaper и свой набор позиций витрины.
//
//  Дисциплина корпуса (правило проекта, не стилистика):
//
//  • Пригласительный код — это маршрут, а не право доступа. Таблицы
//    приглашений в базе нет, проверки на сервере нет. Код открывает
//    нужный вход и подписывает, от кого пришло приглашение — и это
//    всё, что он делает. Так и написано на странице.
//
//  • Партнёру не обещается то, чего у платформы нет. Каждый вход
//    несёт список `limits` — чего в этом предложении не будет.
//
//  • Ставки не публикуются: ни одна не утверждена. Условия берутся
//    из витрины (PriceTerms), а не выдумываются под сегмент.
//
//  • У каждого утверждения о боли сегмента есть основание в `source`.
//    Пробелы помечаются ⟨заполнить⟩ прямо в тексте поля.
// ═══════════════════════════════════════════════════════════════

/** Категория партнёра. Отдельный вход и отдельная пригласительная ссылка. */
export type PartnerSegment =
  | 'industry'        // Промышленность
  | 'infrastructure'  // Инфраструктура
  | 'urban'           // Градостроение и жизнь города
  | 'business'        // Бизнес
  | 'corporate'       // Корпорации
  | 'government'      // Государства и государственные органы
  | 'organization'    // Организации: НКО, международные, отраслевые
  | 'other';          // Иные партнёры: наука, инвесторы, интеграторы

/**
 * Состояние партнёрского входа. Разделено намеренно: страница,
 * которая существует, и работа, которая ведётся, — разные вещи.
 */
export type EntryState =
  | 'open'        // Вход открыт, заявки принимаются
  | 'pilot'       // Открыт для пилота, ограниченный круг
  | 'announced'   // Объявлен, содержание собирается
  | 'draft';      // Черновик, наружу не показывается

/** Шаг приветственной презентации. */
export interface WelcomeStep {
  /** Короткий заголовок шага. */
  title: string;
  /** Что партнёр видит и понимает на этом шаге. */
  body: string;
  /** Куда шаг ведёт внутри платформы, если ведёт. */
  link?: { label: string; path: string };
  /** Числовой факт шага. Берётся из корпуса, не проставляется словами. */
  metric?: { value: string; caption: string };
}

/** Тезис партнёрского whitepaper. */
export interface WhitepaperThesis {
  n: number;
  title: string;
  body: string;
  /** Документ-основание. Обязательно. */
  source: string;
}

/** Что партнёр приносит и что получает. Обмен, а не односторонняя выгода. */
export interface Exchange {
  /** Что партнёр вносит в контур. */
  brings: string[];
  /** Что партнёр получает. Артефакт, а не обещание. */
  gets: string[];
}

export interface PartnerEntry {
  key: PartnerSegment;
  /** Название входа. */
  title: string;
  /** Одна фраза: кому этот вход. */
  lead: string;
  /** Кто именно относится к сегменту. Перечень, а не абстракция. */
  who: string[];
  /**
   * Что у сегмента болит. Каждый пункт — с основанием: либо ссылка
   * на источник в `source`, либо пометка, что это гипотеза контура.
   */
  pains: string[];
  /** Приветственная презентация: 4–7 шагов. */
  welcome: WelcomeStep[];
  /** Онбординг: что партнёр делает по шагам после знакомства. */
  onboarding: string[];
  /** Срез whitepaper под сегмент. */
  theses: WhitepaperThesis[];
  /** Обмен: что вносит, что получает. */
  exchange: Exchange;
  /**
   * Теги для отбора позиций витрины под этот вход. Сверяются с
   * `tags` в SHOWCASE_OFFERINGS — выдуманный тег ничего не покажет.
   */
  offeringTags: string[];
  /** Явные id позиций витрины, которые показываются всегда. */
  pinnedOfferings?: string[];
  /** Домены платформы, релевантные сегменту. */
  domains: string[];
  /** Модули платформы, куда ведёт вход. */
  modules: Array<{ label: string; path: string; note?: string }>;
  /** Чего в этом предложении нет. Граница ответственности. */
  limits: string[];
  state: EntryState;
  /** Уточнение к состоянию: счётчики, оговорки, кто ответственный. */
  stateNote?: string;
  /** Документ-основание для описания сегмента. Обязательно. */
  source: string;
  /** Пригласительный код. Маршрут /invite/:code ведёт на этот вход. */
  inviteCode: string;
  color: string;
  emoji: string;
}

