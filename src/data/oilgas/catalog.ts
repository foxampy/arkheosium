export type ClaimBasis = 'standard' | 'independent' | 'vendor' | 'declared';
export type Stage = 'concept' | 'prototype' | 'pilot' | 'deployed' | 'reference';
export type Pricing = 'quote' | 'subscription' | 'grant' | 'not_published';

export interface CatalogItem {
  id: string;
  title: string;
  /** Одна фраза: что это и зачем. */
  summary: string;
  /** Развёрнутое описание с указанием, откуда взяты числа. */
  description: string;
  stage: Stage;
  pricing: Pricing;
  /** Ключевые параметры. Каждый — с основанием. */
  specs?: Array<{ label: string; value: string; claim: ClaimBasis }>;
  standards?: string[];
  sources?: string[];
  tags?: string[];
  /** Кем разработано: собственная линия или рыночная референция. */
  origin: 'labforge' | 'arkheos' | 'market';
}

