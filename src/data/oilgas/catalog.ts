//
// Дисциплина корпуса та же, что и в водном модуле:
//
// 1. Заявленное называется заявленным. Если цифра пришла из материалов
//    вендора — у неё стоит `claim: 'vendor'`, и в интерфейсе она подписана
//    как заявление производителя, а не как измеренный факт. Независимо
//    подтверждённое — `claim: 'independent'`. Норматив — `claim: 'standard'`.
// 2. Цены не выдумываются. В отрасли почти всё продаётся по запросу под
//    конкретную площадку; поэтому здесь `pricing: 'quote'` — честное «по
//    запросу», а не подставленное правдоподобное число.
// 3. Стадия готовности собственных разработок не завышается. То, что
//    существует как методика и стенд, помечено `stage: 'concept'` или
//    `'prototype'`, а не «серийно».

