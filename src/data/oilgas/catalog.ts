/**
 * Каталожные карточки проектов и корпусные записи проектов — два
 * разных списка, и они намеренно не сливаются в один.
 *
 * Каталожная карточка — это то, что платформа предлагает сделать:
 * у неё есть стадия готовности и модель оплаты, площадка при этом
 * может быть ещё не выбрана. Корпусная запись — это существующий в
 * отрасли проект с координатой, бюджетом, статусом и источниками;
 * платформа его описывает, а не продаёт.
 *
 * Слить их значило бы приписать платформе чужие стройки. Поэтому
 * здесь только счёт и маршрут: раздел каталога называет, сколько
 * нефтегазовых проектов лежит в корпусе, и ведёт туда.
 */
export const OILGAS_PROJECT_CORPUS = {
  count: OILGAS_CORPUS_PROJECTS.length,
  withBudget: OILGAS_CORPUS_PROJECTS.filter((p) => typeof p.budget === 'number' && p.budget > 0).length,
  countries: new Set(OILGAS_CORPUS_PROJECTS.map((p) => p.country_code)).size,
  /**
   * Компактный срез для показа рядом с каталогом. Ведёт на настоящую
   * страницу записи `/hub/project/:id`, а не на список: списочная
   * страница `/hub/projects` читает Supabase, где нефтегазовых проектов
   * нет ни одного — ссылка туда была бы пустой.
   */
  items: OILGAS_CORPUS_PROJECTS.map((p) => ({
    id: p.id,
    title: p.name_ru ?? p.name,
    country: p.country_code,
    region: p.region ?? '',
    status: p.status,
    typeLabel: p.type_label ?? '',
    budget:
      typeof p.budget === 'number' && p.budget > 0
        ? `${(p.budget / 1e9).toFixed(p.budget >= 1e9 ? 2 : 3)} млрд ${p.budget_currency ?? 'USD'}`
        : null,
  })),
} as const;

// Раздел = базовый набор + расширение. Дубли по id снимаются: базовая
// запись выигрывает у одноимённой из расширения, чтобы позиция не
// удвоилась в счётчике каталога.
function mergeSection(base: CatalogItem[], ext: CatalogItem[]): CatalogItem[] {
  const seen = new Set(base.map((i) => i.id));
  return [...base, ...ext.filter((i) => !seen.has(i.id))];
}

