/**
 * Модель токенизации измерений — вторая линия LabForge.
 *
 * Предмет: запечатывание данных измерения в хэш-ноду и эмиссия токена,
 * который эту ноду несёт. Развёртка позиций каталога «Газнефть»:
 * OG-RD-HASH-001 (запечатывание и эмиссия, прототип), OG-EQ-NODE-001
 * (LabForge Node), OG-PR-MRV-001 (проверяемая отчётность, сертификатов
 * выдано 0).
 *
 * Дисциплина корпуса — та же, что в каталоге, и она здесь жёстче обычного,
 * потому что тема граничит с финансовой:
 *
 * 1. Токен не выпущен, сеть узлов не развёрнута, сертификатов не выдано.
 *    Так и написано, в данных, а не в примечании мелким шрифтом.
 * 2. Токен здесь — носитель подтверждённого измерения. Это не финансовый
 *    инструмент, не средство привлечения средств, приём средств не
 *    производится. Оговорка вынесена в NON_FINANCIAL и обязана быть на
 *    видном месте страницы.
 * 3. Ни одной цены, доходности, ставки, эмиссионного объёма и процента
 *    распределения. Их нет — значит, их нет и в данных.
 * 4. Где стандарт к задаче не подходит — это сказано явным полем
 *    `applicability`, а не обойдено молчанием.
 * 5. Пробелы помечены ⟨заполнить⟩ и не заполняются правдоподобным.
 *
 * Типы стадии и основания заимствованы из каталога «Газнефть» импортом
 * только типов (import type стирается при сборке) — чтобы страница
 * токенизации не тянула за собой весь каталог, но говорила на его языке.
 */

