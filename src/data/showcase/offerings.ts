/**
 * Позиции по виду.
 *
 * Учитывается и основной вид, и дополнительные: одна и та же работа
 * бывает одновременно услугой и аудитом, и прятать её из вкладки
 * «Аудит» только потому, что в реестре она записана услугой, —
 * значит потерять её для того, кто ищет аудит.
 */
export function getOfferingsByKind(kind: OfferingKind): ShowcaseOffering[] {
  return SHOWCASE_OFFERINGS.filter(
    (o) => o.kind === kind || (o.alsoKinds?.includes(kind) ?? false),
  );
}

/** Позиции одного поставщика в порядке корпуса. */
export function getOfferingsByProvider(p: ProviderKey): ShowcaseOffering[] {
  return SHOWCASE_OFFERINGS.filter((o) => o.provider === p);
}

/**
 * Счётчики по видам. Сумма больше числа позиций: позиция с
 * дополнительными видами считается в каждом из них — ровно так же,
 * как она отображается во вкладках.
 */
export const SHOWCASE_KIND_COUNTS: Record<OfferingKind, number> = (() => {
  const counts: Record<OfferingKind, number> = {
    service: 0,
    consulting: 0,
    audit: 0,
    rnd: 0,
    development: 0,
    platform: 0,
    solution: 0,
    product: 0,
    research: 0,
    membership: 0,
  };
  for (const o of SHOWCASE_OFFERINGS) {
    counts[o.kind] += 1;
    for (const k of o.alsoKinds ?? []) {
      if (k !== o.kind) counts[k] += 1;
    }
  }
  return counts;
})();
