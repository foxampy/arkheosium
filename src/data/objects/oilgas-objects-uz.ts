//  `oilgas-objects-ext.ts`) описывают Центральную Азию в целом; этот
//  посвящён одной стране. Причина простая: Узбекистан — первый партнёр
//  проекта, и глубина проработки по нему должна быть заметно больше, чем
//  по соседям. Здесь разобраны отдельные месторождения внутри групп,
//  промысловая и транспортная обвязка, разведочные контуры и договорные
//  территории.
//
//  Дисциплина та же, что в `oilgas-objects-ext.ts`, и она здесь важнее
//  количества записей. Каждая запись несёт `coord_precision`:
//
//    exact             — координата самой площадки
//    field_centroid    — точка внутри контура месторождения; контур
//                        занимает десятки километров, точка условна
//    settlement_proxy  — координата ближайшего населённого пункта
//    region_proxy      — только область или плато; ошибка может быть в
//                        сотни километров
//    route_anchor      — для магистрали: опорная точка трассы, а не сама
//                        трасса. Линейный объект точкой не описывается.
//
//  Ни одна координата в этом файле не помечена `exact`: съёмочных точек
//  промысловых площадок в открытых источниках нет, и присвоить их значило
//  бы выдать догадку за измерение. Уровень точности здесь честно ниже, чем
//  в первом файле, — и это факт о состоянии данных, а не недоработка.
//
//  Числа приводятся только там, где есть источник. Где источники спорят,
//  спор сохраняется целиком: мощность Мубарекского ГПЗ (24 / 30 / 31
//  млрд м³/год) и запасы Газли (470 / 500 / 700 / 714 млрд м³) приводятся
//  всеми значениями сразу. Где числа нет — стоит ⟨заполнить⟩, а не
//  правдоподобная величина.
//
//  Заявление оператора называется заявлением, прогноз — прогнозом.
