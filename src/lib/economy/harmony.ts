// Собственно инвариант
// ─────────────────────────────────────────────────────────────────────

/**
 * H = восстановление / изъятие.
 *
 * Про деление на ноль. При нулевом изъятии возвращается Infinity, и это
 * корректно, а не заглушка. Правило 3 запрещает не «низкое H», а
 * превышение изъятия над восстановлением. Если не изымается ничего,
 * превысить нечем: ограничение не нарушено ни при каком восстановлении,
 * включая нулевое. Infinity ≥ 1 истинно, поэтому проверка конституции
 * проходит без отдельной ветки — то есть особый случай не создаёт
 * особого кода, в котором можно было бы спрятать поведение.
 *
 * Случай 0/0 (ничего не изъято и ничего не восстановлено) тоже даёт
 * Infinity, а не NaN, и это тот же самый ответ на тот же вопрос:
 * ограничение не нарушено, потому что изъятия не было. Заметим, что
 * «ничего не изъято» — сильное утверждение о мире; его обоснованность
 * держится на поле source, а не на арифметике.
 *
 * Возвращаемое значение не округляется и не ограничивается сверху.
 * Округление на этом шаге сдвигало бы H = 0,999 к 1 и превращало бы
 * нарушение в соответствие.
 */
export function harmony(withdrawal: number, regeneration: number): number {
  assertPhysical(withdrawal, regeneration);
  if (withdrawal === 0) return Infinity;
  return regeneration / withdrawal;
}

/**
 * Экологический долг: превышение изъятия над восстановлением в ТЕХ ЖЕ
 * физических единицах, в которых поданы аргументы. Ноль, если превышения
 * нет.
 *
 * Правило 4: изъятое сверх восстановления — долг, а не доход. Функция
 * называется debt и возвращает положительное число как величину долга
 * (не как «минус выручку»): долг — самостоятельная величина, а не
 * поправка к денежной строке. В деньгах он не выражается никогда —
 * правило 5.
 *
 * Обратного знака здесь нет намеренно. Если бы функция возвращала
 * отрицательные значения при H > 1, появился бы «профицит», который
 * захотелось бы сложить с долгом другого ресурса или другого периода и
 * зачесть. Зачёта нет: восстановление сверх нормы на одном объекте не
 * гасит пересушенный створ на другом. Поэтому — max(0, …).
 */
export function ecologicalDebt(withdrawal: number, regeneration: number): number {
  assertPhysical(withdrawal, regeneration);
  const excess = withdrawal - regeneration;
  return excess > 0 ? excess : 0;
}

