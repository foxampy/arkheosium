// Проверка конституции (правило 3)
// ─────────────────────────────────────────────────────────────────────

/** Чем именно нарушено правило 3. */
export type ViolationKind =
  /** H < 1: изъятие превышает восстановление. */
  | 'harmony-below-one'
  /** По масштабу нет ни одного замера — соответствие не подтверждено. */
  | 'scale-not-covered';

export interface Violation {
  kind: ViolationKind;
  /** На каком масштабе. Никогда не «в среднем». */
  scale: Scale;
  /** По какому ресурсу. Для 'scale-not-covered' — null: ресурса нет. */
  resource: string | null;
  /** H на этом масштабе по этому ресурсу. Для 'scale-not-covered' — null. */
  h: number | null;
  /** Величина долга в физических единицах. Для 'scale-not-covered' — null. */
  debt: number | null;
  unit: string | null;
  /** Основание данных, на которых обнаружено нарушение. */
  quality: DataQuality | null;
  /** Формулировка на русском: что именно нарушено и почему это нарушение. */
  message: string;
}

export interface ConstitutionCheck {
  ok: boolean;
  violations: Violation[];
}

/**
 * Правило 3 в коде.
 *
 * «Допустим сценарий, где H ≥ 1 одновременно на всех трёх масштабах.
 * Нельзя вывести бассейн в плюс, обнулив отдельный створ, и нельзя
 * оправдать мёртвый створ планетарным балансом.»
 *
 * ───────────────────────────────────────────────────────────────────
 * Почему усреднение между масштабами здесь НЕВОЗМОЖНО, а не просто
 * не сделано.
 *
 * Усреднение требует, чтобы значения разных масштабов встретились в
 * одном выражении: сумма, среднее, взвешенная свёртка — любая операция,
 * принимающая их вместе. В этой функции такого выражения нет и не может
 * появиться незаметно, потому что конструкция устроена так:
 *
 *   1. Каждый замер проверяется поодиночке и порождает СВОЁ нарушение
 *      с прикреплённым к нему масштабом и ресурсом. Значения H никогда
 *      не попадают в общий массив чисел — только в массив объяснений.
 *   2. Итог — логическое И по нарушениям (violations.length === 0),
 *      а не арифметика над H. У логического И нет весов, а значит нет
 *      и ручки, которой один масштаб перевешивает другой.
 *   3. Функция не возвращает никакого агрегированного H, и его не
 *      существует как величины. Нечего усреднять: вызывающий код не
 *      получает отсюда числа, которое выглядело бы как «H сценария».
 *
 * Иными словами, запрет держится не на комментарии «не усредняйте», а
 * на том, что общего числа просто нет. Комментарий снимут при первом
 * рефакторинге; отсутствующую величину придётся сначала ввести, а это
 * видно в диффе.
 *
 * Если кому-то потребуется «общий показатель гармонии» — это и есть
 * ровно та скрытая ручка, которую запрещает правило 10, и ответ на
 * такой запрос — нет.
 * ───────────────────────────────────────────────────────────────────
 *
 * Отдельно: непокрытый масштаб — нарушение, а не умолчание. Если по
 * бассейну замеров нет, сказать «на бассейне всё в порядке» нельзя:
 * основания для такого утверждения не существует. Правило 11 требует
 * называть пробел пробелом, а не заполнять его правдоподобным, поэтому
 * отсутствие данных отклоняет сценарий так же, как H < 1, но с другой
 * формулировкой — чтобы читатель видел разницу между «изымается больше,
 * чем восстанавливается» и «мы не знаем».
 */
export function passesConstitution(readings: readonly ResourceReading[]): ConstitutionCheck {
  const violations: Violation[] = [];

  // Шаг 1. Каждый замер — отдельно. Ни одного выражения, где H одного
  // масштаба встречается с H другого.
  for (const r of readings) {
    const h = harmony(r.withdrawal, r.regeneration);
    if (h < 1) {
      const debt = ecologicalDebt(r.withdrawal, r.regeneration);
      violations.push({
        kind: 'harmony-below-one',
        scale: r.scale,
        resource: r.resource,
        h,
        debt,
        unit: r.unit,
        quality: r.quality,
        message:
          `${SCALE_LABEL[r.scale]} · ${r.resource}: H = ${h.toFixed(3)} < 1. ` +
          `Изъятие превышает восстановление на ${debt} ${r.unit} — это ` +
          `экологический долг (правило 4), а не результат. ` +
          `Основание: ${QUALITY_LABEL[r.quality]}, источник: ${r.source || '⟨заполнить⟩'}.`,
      });
    }
  }

  // Шаг 2. Все три масштаба обязаны быть покрыты. «Одновременно на всех
  // трёх» невыполнимо, если про один из трёх ничего не известно.
  const covered = new Set<Scale>(readings.map((r) => r.scale));
  for (const scale of ['object', 'basin', 'planet'] as const) {
    if (!covered.has(scale)) {
      violations.push({
        kind: 'scale-not-covered',
        scale,
        resource: null,
        h: null,
        debt: null,
        unit: null,
        quality: null,
        message:
          `${SCALE_LABEL[scale]}: замеров нет. Правило 3 требует H ≥ 1 ` +
          `одновременно на всех трёх масштабах; при отсутствии данных ` +
          `соответствие не подтверждено, а не предположено. ⟨заполнить⟩`,
      });
    }
  }

  // Шаг 3. Итог — логическое И. Нарушение на любом одном масштабе есть
  // провал целиком: правило 3 не знает частичного прохождения.
  return { ok: violations.length === 0, violations };
}
