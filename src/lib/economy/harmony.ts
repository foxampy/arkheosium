/**
 * Коэффициент гармонии H — единственный инвариант расчётного слоя.
 *
 * H = восстановление / изъятие.
 *
 * Одна формула, два члена, ни одного коэффициента. Это не упрощение ради
 * читаемости: правило 10 конституции запрещает множители без измеримого
 * источника и опубликованного диапазона, потому что каждый лишний
 * множитель — скрытая ручка. Формула из восьми коэффициентов даёт восемь
 * мест, где результат меняется незаметно для читателя. Здесь таких мест
 * ноль: посторонний, у которого есть два числа, воспроизводит результат
 * в уме и обнаруживает подлог сразу.
 *
 * Почему деление, а не разность. Разность (восстановление − изъятие)
 * зависит от единицы и от размера объекта: −5 м³ на створе и −5 м³ на
 * бассейне — несравнимые величины, а выглядят одинаково. Отношение
 * безразмерно и сравнимо между масштабами, при этом — и это важно — оно
 * сравнимо только с порогом 1, а не между собой (см. ниже про запрет
 * усреднения).
 *
 * Физический долг считается отдельной функцией и в физических единицах:
 * правило 4 требует, чтобы превышение изъятия было названо долгом, а не
 * растворилось в безразмерном отношении.
 *
 * Модуль самостоятелен: ни React, ни зависимостей, ни импортов из корпуса
 * данных. Расчёт, который нельзя запустить отдельно от приложения, нельзя
 * и проверить отдельно от приложения.
 */

// ─────────────────────────────────────────────────────────────────────
// Масштаб и качество данных
// ─────────────────────────────────────────────────────────────────────

/**
 * Три масштаба правила 3. Список закрыт и расширению не подлежит:
 * добавление четвёртого масштаба — это добавление ещё одного места, где
 * можно усреднить неудобный результат.
 */
export type Scale = 'object' | 'basin' | 'planet';

export const SCALE_LABEL: Record<Scale, string> = {
  object: 'объект',
  basin: 'бассейн',
  planet: 'планета',
};

/**
 * Откуда взята величина. Правило 11: утверждение несёт основание.
 *
 * Качество не украшает результат, оно его ограничивает. Вывод, собранный
 * из planetary boundaries, и вывод, собранный со створа с поверенным
 * расходомером, — это разные по силе утверждения, и читатель обязан
 * видеть, какое перед ним, не заглядывая в исходники.
 */
export type DataQuality =
  /** Измерено прибором на объекте: створ, счётчик, расходомер. */
  | 'measured'
  /** Статистика: национальные водные балансы, AQUASTAT, IEA. */
  | 'statistical'
  /** Оценка порядка величины: planetary boundaries и подобное. */
  | 'estimated';

export const QUALITY_LABEL: Record<DataQuality, string> = {
  measured: 'измерено',
  statistical: 'статистика',
  estimated: 'оценка',
};

/**
 * Типичное качество данных для масштаба.
 *
 * Это подсказка составителю, а НЕ значение по умолчанию и не проверка.
 * Качество проставляется явно в каждом замере: если бы оно выводилось из
 * масштаба автоматически, оценка планетарного порядка величины
 * подписывалась бы «измерено» всякий раз, когда кто-то поставил ей
 * scale: 'object'. Основание нельзя вывести из формы записи — его можно
 * только назвать.
 *
 * Порядок ухудшения основания сверху вниз одновременно является порядком
 * роста масштаба, и это не совпадение: чем шире охват, тем дальше
 * величина от прибора.
 */
export const TYPICAL_QUALITY: Record<Scale, DataQuality> = {
  /** Створ, счётчик, расходомер — прибор стоит на объекте. */
  object: 'measured',
  /** Национальные балансы, AQUASTAT, IEA — сводка, а не замер. */
  basin: 'statistical',
  /** Planetary boundaries — оценка порядка величины. */
  planet: 'estimated',
};

/**
 * Насколько качество слабое. Нужно, чтобы при сведении нескольких
 * замеров в один результат брать ХУДШЕЕ основание, а не среднее и не
 * первое попавшееся: утверждение, собранное из измерения и оценки, —
 * это оценка. Сводка не может быть точнее своего слабейшего слагаемого.
 */
const QUALITY_WEAKNESS: Record<DataQuality, number> = {
  measured: 0,
  statistical: 1,
  estimated: 2,
};

/** Худшее (слабейшее) из двух оснований. Ассоциативна, порядок не важен. */
export function weakerQuality(a: DataQuality, b: DataQuality): DataQuality {
  return QUALITY_WEAKNESS[a] >= QUALITY_WEAKNESS[b] ? a : b;
}

// ─────────────────────────────────────────────────────────────────────
// Замер
// ─────────────────────────────────────────────────────────────────────

/**
 * Один замер по одному ресурсу на одном масштабе.
 *
 * Поля `unit`, `quality` и `source` обязательны, а не опциональны, и это
 * сознательная неудобность. Опциональное поле источника означает, что
 * величину можно внести, не называя происхождения, — а именно так
 * выдуманное число попадает в систему: не по злому умыслу, а потому что
 * заполнить поле было не обязательно.
 *
 * `source` — свободная строка, потому что источники разнородны: «створ
 * Чарвак, расходомер №…, 2026-03», «AQUASTAT, показатель…, версия…»,
 * «допущение пользователя, введено в сценарии X». Требование здесь не
 * к формату, а к наличию: пустая строка — ошибка данных.
 */
export interface ResourceReading {
  /** Что измеряется: 'вода', 'энергия', 'CO₂e'. Ключ сведения. */
  resource: string;
  scale: Scale;
  /** Сколько изъято за период. Неотрицательно. */
  withdrawal: number;
  /** Сколько восстановлено за тот же период. Неотрицательно. */
  regeneration: number;
  /** Физическая единица: 'м³/год', 'ГВт·ч/год', 'т CO₂e/год'. */
  unit: string;
  quality: DataQuality;
  /** Откуда величина. Пустая строка недопустима — правило 11. */
  source: string;
}

/**
 * Отрицательное изъятие или отрицательное восстановление — не редкий
 * случай, а сломанные входные данные: изъять минус тысячу кубометров
 * нельзя. Принять такое молча означало бы дать способ «починить» H,
 * подав отрицательное изъятие. Поэтому — исключение, а не нормализация
 * к нулю: нормализация спрятала бы ошибку в данных.
 */
function assertPhysical(withdrawal: number, regeneration: number): void {
  if (!Number.isFinite(withdrawal) || !Number.isFinite(regeneration)) {
    throw new Error(
      'harmony: изъятие и восстановление обязаны быть конечными числами. ' +
        `Получено: изъятие=${withdrawal}, восстановление=${regeneration}.`,
    );
  }
  if (withdrawal < 0 || regeneration < 0) {
    throw new Error(
      'harmony: отрицательное изъятие или восстановление физически ' +
        'невозможно и здесь не нормализуется к нулю, потому что ' +
        'нормализация спрятала бы ошибку во входных данных. ' +
        `Получено: изъятие=${withdrawal}, восстановление=${regeneration}.`,
    );
  }
}

