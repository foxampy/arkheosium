/**
 * Сколько людей сценарий обеспечивает названной потребностью.
 *
 * Если потребность в сценарии не встречается — ноль, а не пропуск.
 * Сценарий, не дающий людям воды, не «не участвует в сравнении по
 * воде», он даёт ноль, и в ранжировании стоит соответственно.
 */
function peopleFor(result: ScenarioResult, need: string): number {
  const entry = result.needsCovered.byNeed.find((n) => n.need === need);
  return entry ? entry.people : 0;
}

/** Первое нарушение как короткая причина. Остальные — в списке violations. */
function shortReason(violations: readonly Violation[]): string {
  const first = violations[0];
  if (!first) return 'Причина не определена — это ошибка движка, а не сценария.';
  if (first.kind === 'scale-not-covered') {
    return `Нет данных по масштабу «${SCALE_LABEL[first.scale]}»`;
  }
  return `H < 1 на масштабе «${SCALE_LABEL[first.scale]}» по ресурсу «${first.resource}»`;
}

/**
 * Золотой путь: фильтр плюс сортировка, четыре шага, каждый видимый.
 *
 * Шаг 1. Оценить все сценарии одинаково — evaluateScenario, без
 *        исключений и без предварительного отбора. Сценарий не может
 *        быть «не рассмотрен».
 * Шаг 2. Разделить по constitution.ok. Отсеянные НЕ выбрасываются: у
 *        каждого названа причина и сохранён полный список нарушений.
 *        Выброшенный сценарий — это утверждение «он не рассматривался»,
 *        сделанное молча; здесь такого утверждения сделать нельзя.
 * Шаг 3. Прошедшие отранжировать по покрытию потребностей, а не по
 *        деньгам. Это прямое следствие правил 3 и 5: деньги — одна из
 *        колонок, и она не главнее другой, а сортировка по деньгам
 *        сделала бы её главнее де-факто, ничего не объявляя.
 * Шаг 4. Вернуть оба списка с объяснением по каждому элементу.
 *
 * @param need  По какой потребности ранжировать. Параметр обязателен и
 *              не имеет значения по умолчанию: умолчание — это тот же
 *              скрытый коэффициент, только в виде выбора признака.
 *              Кто ранжирует, тот и называет признак вслух.
 *
 * Устойчивость порядка. При равном числе людей сценарии упорядочены по
 * id лексикографически. Это произвольное правило, и оно объявлено
 * именно поэтому: произвольное правило, объявленное вслух, не даёт
 * повода думать, что за порядком стоит скрытое суждение о качестве.
 * Ни выручка, ни долг в тай-брейк не входят — иначе деньги вернулись бы
 * в сортировку через заднюю дверь.
 */
export function goldenPath(
  scenarios: readonly Scenario[],
  need: string,
): GoldenPathResult {
  // Шаг 1.
  const evaluated = scenarios.map(evaluateScenario);

  // Шаг 2.
  const passed: ScenarioResult[] = [];
  const rejected: RejectedScenario[] = [];

  for (const result of evaluated) {
    if (result.constitution.ok) {
      passed.push(result);
      continue;
    }
    const violations = result.constitution.violations;
    rejected.push({
      result,
      violations,
      reason: shortReason(violations),
      explanation:
        `Сценарий «${result.scenarioTitle}» отсеян правилом 3: изъятие не ` +
        `должно превышать восстановления одновременно на всех трёх ` +
        `масштабах. Нарушений — ${violations.length}. ` +
        violations.map((v) => v.message).join(' ') +
        ` Сценарий сохранён в списке отсеянных: из того, что вариант ` +
        `рассматривался и не прошёл, следует больше, чем из его отсутствия.`,
    });
  }

  // Шаг 3.
  const ranked = [...passed].sort((a, b) => {
    const byPeople = peopleFor(b, need) - peopleFor(a, need);
    if (byPeople !== 0) return byPeople;
    // Объявленный тай-брейк. Сравнение строк, а не чисел: ни одна
    // экономическая величина сюда не допущена.
    return a.scenarioId.localeCompare(b.scenarioId, 'ru');
  });

  const passedOut: PassedScenario[] = ranked.map((result, i) => {
    const people = peopleFor(result, need);
    const debtNote =
      result.ecological.debt.length === 0
        ? 'Экологического долга нет ни по одному ресурсу.'
        : `Долг: ${result.ecological.debt
            .map((d) => `${d.amount} ${d.unit} (${d.resource}, ${SCALE_LABEL[d.scale]})`)
            .join(', ')}.`;
    return {
      result,
      rank: i + 1,
      rankValue: people,
      rankedBy: need,
      explanation:
        `Сценарий «${result.scenarioTitle}» прошёл конституцию: H ≥ 1 на ` +
        `всех трёх масштабах по всем заявленным ресурсам. ` +
        `Место ${i + 1} — по числу людей, обеспеченных потребностью ` +
        `«${need}»: ${people}. Выручка ${result.economic.revenue} USD в ` +
        `ранжировании не участвует (правило 5: деньги и среда не сводятся ` +
        `в одну величину, и сортировка по деньгам сделала бы денежную ` +
        `колонку главной, ничего об этом не объявив). ${debtNote} ` +
        `Основание расчёта — допущения сценария: ${result.assumptions}`,
    };
  });

  // Шаг 4.
  return {
    rankedBy: need,
    passed: passedOut,
    rejected,
    method:
      'Фильтр и сортировка, без целевой функции и без весов. ' +
      '1) Каждый сценарий оценён одинаково. ' +
      '2) Разделение по правилу 3: H ≥ 1 одновременно на масштабах ' +
      'объекта, бассейна и планеты; нарушение на любом одном — отсев целиком. ' +
      `3) Прошедшие упорядочены по числу людей, обеспеченных потребностью «${need}», ` +
      'при равенстве — по идентификатору сценария. ' +
      '4) Отсеянные сохранены с полным перечнем нарушений. ' +
      'Скрытой модели нет: результат воспроизводится вручную из входных чисел.',
    dataState: NO_DATA,
  };
}

