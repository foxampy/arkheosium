/**
 * Золотой путь — выбор сценария на глазах у всех.
 *
 * ───────────────────────────────────────────────────────────────────
 * Чем это не является.
 *
 * Это не оптимизатор. Здесь нет целевой функции, нет весов, нет
 * подбора, нет обучения на истории. Всё, что происходит ниже, — фильтр
 * и сортировка: сценарии проверяются конституцией, непрошедшие
 * откладываются с названной причиной, прошедшие выстраиваются по одному
 * объявленному признаку.
 *
 * Почему именно так, а не «лучше». Оптимизатор устроен как чёрный ящик
 * по своей природе: он принимает веса, а веса — это коэффициенты без
 * измеримого источника, которые правило 10 запрещает прямым текстом.
 * Множитель, поставленный внутрь целевой функции, меняет ответ
 * незаметно для читателя: снаружи видно только «модель рекомендует»,
 * и проверить это нельзя, не имея самой модели. Скрытая модель — и есть
 * ровно та ручка, которую правило 10 закрывает, а «оптимальный путь,
 * рассчитанный системой» — самая удобная формулировка для того, чтобы
 * повернуть её от чужого имени.
 *
 * Поэтому оптимум здесь выбирается открыто. Прозрачность в этом модуле
 * важнее мощности: слабый метод, который посторонний воспроизводит
 * вручную на листе бумаги, защищает лучше, чем сильный, который
 * приходится принимать на слово. Если алгоритм отсеял сценарий, из
 * результата видно, какой замер это сделал и на каком масштабе; если
 * поставил один выше другого — видно, по какому числу.
 * ───────────────────────────────────────────────────────────────────
 */

