/** Сценарий, прошедший конституцию. */
export interface PassedScenario {
  result: ScenarioResult;
  /** Место в ранжировании, начиная с 1. */
  rank: number;
  /** Число, по которому сценарий поставлен на это место. */
  rankValue: number;
  /** По какой потребности ранжировали. Названо явно, а не подразумевается. */
  rankedBy: string;
  /** Почему сценарий прошёл и почему стоит именно здесь. Фраза на русском. */
  explanation: string;
}

/** Сценарий, отсеянный конституцией. Не выбрасывается. */
export interface RejectedScenario {
  result: ScenarioResult;
  /** Нарушения целиком, как их вернула конституция. */
  violations: Violation[];
  /** Короткая причина отсева одной фразой. */
  reason: string;
  /** Развёрнутое объяснение: что именно и на каком масштабе. */
  explanation: string;
}

export interface GoldenPathResult {
  /** По какой потребности ранжировались прошедшие. */
  rankedBy: string;
  passed: PassedScenario[];
  /** Отсеянные сохранены с причиной. Список никогда не скрывается в UI. */
  rejected: RejectedScenario[];
  /** Как именно получен этот результат. Метод, а не реклама метода. */
  method: string;
  /** Состояние данных на момент расчёта. */
  dataState: typeof NO_DATA;
}

