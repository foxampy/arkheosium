/**
 * Сколько реальных замеров в системе.
 *
 * Ноль. Не «мало», не «пока ограниченно», не «на этапе наполнения» —
 * ноль. Ни один створ не подключён, ни один расходомер не передаёт
 * показания, ни одна строка национального баланса не импортирована.
 * Правило 11 требует, чтобы ноль был написан нулём: пропущенный ноль
 * читается как отсутствие темы, а не как отсутствие величины, и именно
 * так «замеров 0» превращается в ощущение, что замеры есть.
 *
 * Что из этого следует для движка. Он считает ИСКЛЮЧИТЕЛЬНО то, что
 * подано ему на вход как допущение пользователя. Ни одна функция этого
 * пакета не обращается к внешнему источнику, не читает базу и не несёт
 * встроенных значений. Результат расчёта имеет ровно ту силу, какую
 * имеют введённые числа, — и ни каплей больше: красивая структура
 * ответа не добавляет основания входным данным.
 *
 * Демонстрационных наборов, выглядящих как настоящие, в пакете нет.
 * Единственный пример назван примером в имени переменной (EXAMPLE_*)
 * и в комментарии над ней, и его числа ничего не утверждают о мире.
 */
